#!/usr/bin/env python3
"""
Generates NotoSans-Regular.ttf.h, the default font embedded in ChaiLove.

Only the printable ASCII glyphs are kept, as those are all pntr bakes when
PNTR_ENABLE_UTF8 is not defined. Widen UNICODES if that ever changes.

Usage:
    pip install fonttools
    python3 generate.py path/to/NotoSans-Regular.ttf

Use the unhinted NotoSans-Regular.ttf from the Noto Sans release:
https://github.com/notofonts/latin-greek-cyrillic/releases/tag/NotoSans-v2.015
"""

import io
import os
import sys

from fontTools import subset

UNICODES = range(0x20, 0x7F)
GUARD = 'SRC_LOVE_TYPES_GRAPHICS_FONTS_NOTOSANS_REGULAR_TTF_H_'


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)

    options = subset.Options()
    options.layout_features = []
    options.hinting = False
    options.drop_tables += ['GSUB', 'GPOS', 'GDEF', 'DSIG']

    font = subset.load_font(sys.argv[1], options)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=UNICODES)
    subsetter.subset(font)

    output = io.BytesIO()
    subset.save_font(font, output, options)
    data = output.getvalue()

    lines = [
        '// Noto Sans Regular 2.015 (unhinted), subset to printable ASCII.',
        '// The default font in LOVE 12. Generated by generate.py.',
        '// See NotoSans-OFL.txt for its license.',
        '#ifndef ' + GUARD,
        '#define ' + GUARD,
        '',
        'static const unsigned char NotoSans_Regular_ttf[] = {',
    ]
    for i in range(0, len(data), 16):
        lines.append('\t' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',')
    lines += [
        '};',
        '',
        'static const unsigned int NotoSans_Regular_ttf_len = %d;' % len(data),
        '',
        '#endif  // ' + GUARD,
        '',
    ]

    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'NotoSans-Regular.ttf.h')
    with open(path, 'w') as f:
        f.write('\n'.join(lines))
    print('Wrote %s (%d bytes)' % (path, len(data)))


if __name__ == '__main__':
    main()
